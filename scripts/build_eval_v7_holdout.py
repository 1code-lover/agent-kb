def _base_case(*, case_id: str, kb_id: str, question: str, source_doc: str | None, source_locator: str | None,
               modality: str, answer_style: str, difficulty: str, category: str, answerable: bool,
               expected_keypoints: list[str], required_evidence_docs: list[str], expected_source_count: int,
               preview_required: bool, preview_terms: list[str], forbidden_terms: list[str],
               judge_focus: list[str], seed_docs: list[str] | None = None) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "dataset": DATASET_NAME,
        "expected_scope_type": "single_kb",
        "expected_isolation_level": "physical_isolated",
        "case_id": case_id,
        "kb_id": kb_id,
        "question": question,
        "source_doc": source_doc,
        "source_locator": source_locator,
        "modality": modality,
        "answer_style": answer_style,
        "difficulty": difficulty,
        "category": category,
        "answerable": answerable,
        "expected_keypoints": expected_keypoints,
        "required_evidence_docs": required_evidence_docs,
        "expected_source_count": expected_source_count,
        "preview_required": preview_required,
        "preview_terms": preview_terms,
        "forbidden_terms": forbidden_terms,
        "judge_focus": judge_focus,
    }
    if seed_docs:
        payload["seed_docs"] = seed_docs
    return payload


