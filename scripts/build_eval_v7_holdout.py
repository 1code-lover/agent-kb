    parser.add_argument("--output-dir", default="tests/fixtures/rag_quality/eval_v7")
    args = parser.parse_args()

    output_dir = Path(args.output_dir)
    schema = build_schema()
    cases = build_cases()
    _write_json(output_dir / "schema.json", schema)
    _write_json(output_dir / "cases.json", cases)

